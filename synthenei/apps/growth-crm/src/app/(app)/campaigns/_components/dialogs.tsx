"use client";
import { useMemo, useState, useTransition } from "react";
import { Plus, Upload } from "lucide-react";
import { Dialog, DialogClose, DialogContent, DialogTrigger } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { createCampaign, importCampaignCsv } from "../_actions";
import { MktGate, notify } from "./action";

const field = "h-9 w-full rounded-sm border border-line-strong bg-surface px-2.5 text-[13px] text-ink outline-none focus:border-ring";
const lbl = "mb-1 block text-[12px] font-medium text-ink-2";

export const PLATFORMS = [
  { key: "linkedin", label: "LinkedIn Campaign Manager", cols: "Campaign name, Date, Impressions, Clicks, Total spent, Leads" },
  { key: "meta", label: "Meta Ads Manager", cols: "Campaign name, Day, Reach, Impressions, Link clicks, Amount spent (INR), Leads" },
  { key: "google_ads", label: "Google Ads", cols: "Campaign, Day, Impr., Clicks, Cost, Conversions" },
  { key: "email", label: "Mailchimp", cols: "Campaign, Send date, Emails sent, Unique opens, Unique clicks, Unsubscribes" },
  { key: "whatsapp", label: "WhatsApp (BSP export)", cols: "Template, Date, Sent, Delivered, Read, Replied, Cost" },
] as const;

/** CSV import with a column-mapping preview (spec 3b). Rows for unknown campaigns are rejected server-side. */
export function ImportCsvDialog({ campaigns, campaignId }: { campaigns: { id: string; name: string; channel: string }[]; campaignId?: string }) {
  const fixed = campaigns.find((c) => c.id === campaignId);
  const [platform, setPlatform] = useState<string>(fixed?.channel ?? "linkedin");
  const [pending, start] = useTransition();
  const p = PLATFORMS.find((x) => x.key === platform)!;
  return (
    <Dialog>
      <MktGate can="importCsv"><DialogTrigger asChild><Button><Upload />{campaignId ? "Import daily metrics" : "Import results CSV"}</Button></DialogTrigger></MktGate>
      <DialogContent title={campaignId ? `Import daily metrics: ${fixed?.name ?? ""}` : "Import campaign results"} description="Upload a platform export. You will see the column mapping before anything is written.">
        <div className="space-y-4">
          <div>
            <label className={lbl} htmlFor="imp-platform">Platform template</label>
            <select id="imp-platform" className={field} value={platform} onChange={(e) => setPlatform(e.target.value)} disabled={!!fixed}>
              {PLATFORMS.map((x) => <option key={x.key} value={x.key}>{x.label}</option>)}
            </select>
          </div>
          <div className="rounded-sm border border-line bg-paper px-3 py-2 text-[12px] text-ink-2">
            <div className="font-medium text-ink">Expected columns</div>
            <div className="mt-0.5 font-mono text-[11px] leading-5 text-ink-3">{p.cols}</div>
            <div className="mt-1.5">Campaign is matched on <span className="font-mono text-[11px]">utm_campaign</span> or the exact campaign name. Unmatched rows are listed and skipped.</div>
          </div>
          <div>
            <label className={lbl} htmlFor="imp-file">File (.csv, max 5 MB)</label>
            <input id="imp-file" type="file" accept=".csv,text/csv" className="block w-full text-[12px] text-ink-2 file:mr-3 file:h-8 file:rounded-sm file:border file:border-line-strong file:bg-surface file:px-3 file:text-[12px] file:text-ink" />
          </div>
          <div className="flex justify-end gap-2">
            <DialogClose asChild><Button variant="ghost">Cancel</Button></DialogClose>
            <DialogClose asChild>
              <Button variant="primary" disabled={pending} onClick={() => start(async () => notify(await importCampaignCsv(p.label, campaignId)))}>Preview mapping</Button>
            </DialogClose>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}

const CH_ABBR: Record<string, string> = { linkedin: "li", whatsapp: "wa", email: "em", meta: "meta", google_ads: "gads" };
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/(^_|_$)/g, "");

/** New campaign: UTM is generated by the convention {channel}_{district|statewide}_{theme}_{yyyymm} (spec 3b). */
export function NewCampaignDialog({ districts, yyyymm }: { districts: string[]; yyyymm: string }) {
  const [name, setName] = useState("");
  const [channel, setChannel] = useState("linkedin");
  const [district, setDistrict] = useState("statewide");
  const [theme, setTheme] = useState("");
  const [budget, setBudget] = useState("");
  const [pending, start] = useTransition();
  const utm = useMemo(() => `${CH_ABBR[channel]}_${slug(district)}_${slug(theme) || "theme"}_${yyyymm}`, [channel, district, theme, yyyymm]);
  return (
    <Dialog>
      <MktGate can="editCampaigns"><DialogTrigger asChild><Button variant="primary"><Plus />New campaign</Button></DialogTrigger></MktGate>
      <DialogContent title="New campaign" description="Leads are attributed by the UTM below, so keep it as generated.">
        <form className="space-y-3" onSubmit={(e) => { e.preventDefault(); start(async () => notify(await createCampaign({ name, channel, district, theme, budget: Number(budget) }))); }}>
          <div><label className={lbl} htmlFor="nc-name">Name</label><input id="nc-name" className={field} value={name} onChange={(e) => setName(e.target.value)} placeholder="Madurai Bench hearings — senior advocates" required /></div>
          <div className="grid gap-3 sm:grid-cols-2">
            <div><label className={lbl} htmlFor="nc-ch">Channel</label>
              <select id="nc-ch" className={field} value={channel} onChange={(e) => setChannel(e.target.value)}>
                <option value="linkedin">LinkedIn</option><option value="whatsapp">WhatsApp</option><option value="email">Mailchimp</option><option value="meta">Meta</option><option value="google_ads">Google Ads</option>
              </select></div>
            <div><label className={lbl} htmlFor="nc-d">District</label>
              <select id="nc-d" className={field} value={district} onChange={(e) => setDistrict(e.target.value)}>
                <option value="statewide">Statewide</option>{districts.map((d) => <option key={d} value={d}>{d}</option>)}
              </select></div>
            <div><label className={lbl} htmlFor="nc-t">Theme</label><input id="nc-t" className={field} value={theme} onChange={(e) => setTheme(e.target.value)} placeholder="hearings" /></div>
            <div><label className={lbl} htmlFor="nc-b">Budget (₹)</label><input id="nc-b" inputMode="numeric" className={field + " num text-right"} value={budget} onChange={(e) => setBudget(e.target.value.replace(/[^\d]/g, ""))} placeholder="75000" required /></div>
          </div>
          <div className="rounded-sm border border-line bg-paper px-3 py-2"><div className="text-[11px] text-ink-3">utm_campaign</div><div className="font-mono text-[13px] text-ink">{utm}</div></div>
          <div className="flex justify-end gap-2 pt-1">
            <DialogClose asChild><Button type="button" variant="ghost">Cancel</Button></DialogClose>
            <Button type="submit" variant="primary" disabled={pending}>Create campaign</Button>
          </div>
        </form>
      </DialogContent>
    </Dialog>
  );
}
